"""PEP 517 hook and strict canonical Skill inventory (stdlib only).

The shared methods remain editable only in skills/deck-master/references.
The package's historical resources/skill path is retained; other public
entries contain no copies of those methods.
"""
from pathlib import Path
import ast
import hashlib
import json
import shutil
import tomllib

from setuptools.command.build_py import build_py

PUBLIC_SKILLS = ('deck-master', 'deck-content', 'deck-design', 'deck-review')
REFERENCE_NAMES = (
    'blueprint-svg', 'style-calibration', 'icon-quality', 'content-examples',
    'review-and-repair', 'visual-reference', 'content-calibration',
    'source-reading', 'installation', 'input-update', 'candidates-and-stages',
    'content-methods', 'collaboration-routing', 'physical-units',
)
INVENTORY_PATH = 'deck_master/resources/method-inventory.json'
GENERATED_EXCEPTIONS = {
    INVENTORY_PATH: 'Generated by tools/build_hook.py from the exhaustive canonical Skill mapping; no editable source copy.',
}


def source_version(root):
    root = Path(root)
    version = tomllib.loads((root / 'pyproject.toml').read_text())['project']['version']
    module = ast.parse((root / 'src/deck_master/__init__.py').read_text())
    declared = next((node.value.value for node in module.body if isinstance(node, ast.Assign)
                     and any(isinstance(target, ast.Name) and target.id == '__version__' for target in node.targets)
                     and isinstance(node.value, ast.Constant)), None)
    if declared != version:
        raise RuntimeError('source __version__ differs from pyproject version')
    return version


def canonical_mapping(root):
    """Fail on missing, unlisted or symlink canonical files; no count heuristic."""
    root = Path(root)
    mapping = {'deck_master/resources/skills/RESOLVER.md': 'skills/RESOLVER.md'}
    for skill in PUBLIC_SKILLS:
        target = 'deck_master/resources/skill' if skill == 'deck-master' else f'deck_master/resources/skills/{skill}'
        for relative in ('SKILL.md', 'agents/openai.yaml'):
            mapping[f'{target}/{relative}'] = f'skills/{skill}/{relative}'
    for name in REFERENCE_NAMES:
        mapping[f'deck_master/resources/skill/references/{name}.md'] = f'skills/deck-master/references/{name}.md'
    actual = set()
    for path in (root / 'skills').rglob('*'):
        if path.is_symlink():
            raise RuntimeError(f'canonical Skill symlink is forbidden: {path}')
        if path.is_file():
            actual.add(path.relative_to(root).as_posix())
    expected = set(mapping.values())
    if actual != expected:
        raise RuntimeError(f'canonical Skill inventory mismatch; unknown={sorted(actual - expected)}, missing={sorted(expected - actual)}')
    return mapping


def resource_inventory(root):
    mapping = canonical_mapping(root)
    return {
        'schema_version': 'method_resource_inventory.v1',
        'public_skills': list(PUBLIC_SKILLS),
        'shared_method_source': 'skills/deck-master/references',
        'files': {target: {'canonical_source': source,
                           'sha256': hashlib.sha256((Path(root) / source).read_bytes()).hexdigest()}
                  for target, source in sorted(mapping.items())},
        'generated_exceptions': GENERATED_EXCEPTIONS,
    }


def validate_wheel_inventory(archive, *, root=None):
    """Validate every Skill/method wheel member, including exact source bytes."""
    names = archive.namelist()
    if len(names) != len(set(names)):
        raise RuntimeError('duplicate wheel members')
    inventory = json.loads(archive.read(INVENTORY_PATH))
    if inventory.get('schema_version') != 'method_resource_inventory.v1':
        raise RuntimeError('unsupported method inventory')
    if inventory.get('generated_exceptions') != GENERATED_EXCEPTIONS:
        raise RuntimeError('unknown generated method resource exception')
    if inventory.get('public_skills') != list(PUBLIC_SKILLS):
        raise RuntimeError('public Skill inventory mismatch')
    if root is not None and inventory != resource_inventory(root):
        raise RuntimeError('wheel canonical resource mapping or hashes differ from source')
    expected = set(inventory['files'])
    actual = {name for name in names if not name.endswith('/') and
              (name.startswith('deck_master/resources/skill/') or name.startswith('deck_master/resources/skills/'))}
    if actual != expected:
        raise RuntimeError(f'wheel Skill inventory mismatch; unknown={sorted(actual - expected)}, missing={sorted(expected - actual)}')
    for name, row in inventory['files'].items():
        if hashlib.sha256(archive.read(name)).hexdigest() != row['sha256']:
            raise RuntimeError(f'wheel method hash mismatch: {name}')
    return inventory


class BuildPy(build_py):
    def run(self):
        root = Path(__file__).resolve().parents[1]
        source_version(root)
        inventory = resource_inventory(root)
        for name in ('index.html', 'app.js', 'style.css'):
            (Path(self.build_lib) / 'deck_master/resources/static' / name).unlink(missing_ok=True)
        super().run()
        # Remove stale warm-build resources before copying the complete mapping.
        for name in ('skill', 'skills', 'skills-references'):
            retired = Path(self.build_lib) / 'deck_master/resources' / name
            if retired.is_symlink():
                retired.unlink()
            elif retired.exists():
                shutil.rmtree(retired)
        for target, row in inventory['files'].items():
            destination = Path(self.build_lib) / target
            destination.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(root / row['canonical_source'], destination)
        (Path(self.build_lib) / INVENTORY_PATH).write_text(
            json.dumps(inventory, ensure_ascii=False, indent=2, sort_keys=True) + '\n', encoding='utf-8')
