"""Render the shipped token sheet from its reviewed JSON source (no dependencies)."""
import argparse
import json
from pathlib import Path

STATIC = Path(__file__).resolve().parents[1] / 'src/deck_master/resources/static/v2'


def render():
    data = json.loads((STATIC / 'tokens.json').read_text())
    lines = ['/* Generated by tools/generate_ui_tokens.py; edit tokens.json. */', ':root {']
    for group in ('tokens', 'compatibility_aliases'):
        lines.append('  /* ' + group + ' */')
        lines.extend(f'  {name}: {value};' for name, value in data[group].items())
    return '\n'.join(lines + ['}', ''])


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    path = STATIC / 'tokens.css'
    content = render()
    if args.check:
        if path.read_text() != content:
            raise SystemExit('tokens.css differs from tokens.json; run tools/generate_ui_tokens.py')
    else:
        path.write_text(content)
